async function seed() {
  console.log(`🌱 Seeding ${CREATORS.length} minor creator accounts...\n`)
  let created = 0, skipped = 0

  for (const creator of CREATORS) {
    process.stdout.write(`→ ${creator.full_name} (${creator.country})`)

    const { data: authData, error: authErr } = await supabase.auth.admin.createUser({
      email: creator.email,
      password: "Creator@2026!",
      email_confirm: true,
      user_metadata: {
        full_name: creator.full_name,
        role: "creator",
        is_testimonial: creator.testimonial,
        testimonial_quote: creator.quote,
        avatar_img: creator.avatar_img,
      },
    })

    if (authErr) {
      if (authErr.message?.includes("already") ) {
        process.stdout.write(" ⚠️  exists\n")
        skipped++
        continue
      }
      process.stdout.write(` ✗ ${authErr.message}\n`)
      continue
    }

    const userId = authData.user.id
    await new Promise((r) => setTimeout(r, 600))

    const avatarUrl = `https://i.pravatar.cc/150?img=${creator.avatar_img}`

    // Update profiles row
    await supabase.from("profiles").update({
      role: "user",
      full_name: creator.full_name,
      avatar_url: avatarUrl,
      photo_url: avatarUrl,
    }).eq("id", userId)

    // Create creator_profiles row
    const { error: cpErr } = await supabase.from("creator_profiles").upsert({
      user_id: userId,
      display_name: creator.full_name,
      bio: creator.bio,
      country: creator.country,
      city: creator.city,
      languages: creator.languages,
      categories: creator.categories,
      content_types: creator.content_types,
      tiktok_handle: creator.tiktok_handle,
      tiktok_followers: creator.tiktok_followers,
      tiktok_avg_views: creator.tiktok_avg_views,
      instagram_handle: creator.instagram_handle,
      instagram_followers: creator.instagram_followers,
      youtube_subscribers: creator.youtube_subscribers,
      base_rate_cents: creator.base_rate_cents,
      currency: "USD",
      platform_rating: creator.platform_rating,
      total_campaigns_completed: creator.total_campaigns_completed,
      total_earnings_cents: creator.total_earnings_cents,
      age_verified: true,
      tax_form_type: "W-8BEN",
      tax_form_submitted: true,
      is_featured: false,
      ai_match_score: Math.round(creator.platform_rating * 18),
    }, { onConflict: "user_id" })

    if (cpErr) {
      process.stdout.write(` ✗ profile: ${cpErr.message}\n`)
    } else {
      process.stdout.write(` ✓\n`)
      created++
    }
  }

  console.log(`\n✅ Done — ${created} created, ${skipped} already existed.`)
}

